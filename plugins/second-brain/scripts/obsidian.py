GROUP_COLORS = {"wiki": 8073150, "raw": 3113197, "output": 15898954}
HUB_START = "<!-- GENERATED BY second-brain obsidian -->"
HUB_END = "<!-- END second-brain obsidian -->"
GITIGNORE_BLOCK = """# Obsidian device and session state. Track the remaining vault settings.
.obsidian/workspace.json
.obsidian/workspaces.json
.obsidian/workspace-mobile.json
# Generated from config/obsidian/graph.json by /second-brain obsidian.
.obsidian/graph.json
"""


def discover_brains(project: Path) -> list[Path]:
    brains = []
    if (project / "wiki" / "index.md").is_file():
        brains.append(project)
    brains_dir = project / "brains"
    if brains_dir.is_dir():
        brains.extend(
            index.parent.parent
            for index in brains_dir.rglob("wiki/index.md")
            if not any(
                part.startswith(".") or part == "_template"
                for part in index.relative_to(brains_dir).parts
            )
        )
    return sorted(set(brains), key=lambda path: path.relative_to(project).as_posix())


def brain_name(project: Path, brain: Path) -> str:
    relative = brain.relative_to(project).as_posix()
    return "root" if relative == "." else relative.removeprefix("brains/")


def select_brain(project: Path, brains: list[Path], selector: str) -> Path:
    matches = [
        brain
        for brain in brains
        if selector in {
            brain_name(project, brain),
            brain.relative_to(project).as_posix(),
            brain.name,
        }
    ]
    if len(matches) != 1:
        names = ", ".join(brain_name(project, brain) for brain in brains) or "none"
        reason = "is ambiguous" if matches else "was not found"
        raise ValueError(f"Brain '{selector}' {reason}. Available brains: {names}")
    return matches[0]


def write_json_if_missing(path: Path, value: object) -> bool:
    if path.exists():
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2) + "\n")
    return True


def graph_config(project: Path, brains: list[Path]) -> dict:
    path = project / "config" / "obsidian" / "graph.json"
    runtime = project / ".obsidian" / "graph.json"
    source = path if path.exists() else runtime if runtime.exists() else None
    if source:
        try:
            config = json.loads(source.read_text())
        except (json.JSONDecodeError, OSError) as error:
            raise ValueError(f"Cannot read {source}: {error}") from error
        if not isinstance(config, dict):
            raise ValueError(f"Expected a JSON object in {source}")
    else:
        config = dict(GRAPH_DEFAULTS)
        config["colorGroups"] = []

    groups = config.setdefault("colorGroups", [])
    if not isinstance(groups, list):
        raise ValueError(f"Expected colorGroups to be a list in {path}")
    queries = {group.get("query") for group in groups if isinstance(group, dict)}
    for brain in brains:
        prefix = brain.relative_to(project)
        for directory, color in GROUP_COLORS.items():
            query = f"path:{(prefix / directory).as_posix()}"
            if query not in queries:
                groups.append({"query": query, "color": {"a": 1, "rgb": color}})
                queries.add(query)

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(config, indent=2) + "\n")
    runtime.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(path, runtime)
    return config


def update_gitignore(project: Path) -> None:
    path = project / ".gitignore"
    content = path.read_text() if path.exists() else ""
    existing = content.splitlines()
    missing = [line for line in GITIGNORE_BLOCK.splitlines() if line and line not in existing]
    if not any(not line.startswith("#") for line in missing):
        return
    separator = "" if not content or content.endswith("\n") else "\n"
    addition = "\n".join(missing) + "\n"
    path.write_text(content + separator + ("\n" if content else "") + addition)


def update_hub(project: Path, brains: list[Path]) -> Path:
    path = project / "brains" / "index.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    links = []
    for brain in brains:
        relative = (brain / "wiki" / "index.md").relative_to(project).with_suffix("")
        links.append(f"- [[{relative.as_posix()}|{brain_name(project, brain)}]]")
    generated = f"{HUB_START}\n# Brain Index\n\n" + "\n".join(links) + f"\n{HUB_END}"
    content = path.read_text() if path.exists() else ""
    if HUB_START in content and HUB_END in content:
        before, rest = content.split(HUB_START, 1)
        _, after = rest.split(HUB_END, 1)
        content = before + generated + after
    else:
        separator = "" if not content else "\n\n"
        content += separator + generated + "\n"
    path.write_text(content)
    return path


def open_in_obsidian(path: Path) -> None:
    url = "obsidian://open?path=" + quote(str(path), safe="/")
    if sys.platform == "darwin":
        command = ["open", url]
    elif os.name == "nt":
        command = ["cmd", "/c", "start", "", url]
    else:
        command = ["xdg-open", url]
    subprocess.run(command, check=True)


def prepare(project: Path, selector: str | None, should_open: bool) -> Path:
    project = project.expanduser().resolve()
    if not project.is_dir():
        raise ValueError(f"Project directory does not exist: {project}")
    brains = discover_brains(project)
    if not brains:
        raise ValueError("No brain found. Expected wiki/index.md or brains/<name>/wiki/index.md")

    obsidian = project / ".obsidian"
    write_json_if_missing(obsidian / "app.json", {})
    write_json_if_missing(obsidian / "appearance.json", {})
    write_json_if_missing(obsidian / "core-plugins.json", CORE_PLUGINS)
    graph_config(project, brains)
    update_gitignore(project)

    if selector:
        target = select_brain(project, brains, selector) / "wiki" / "index.md"
    elif len(brains) == 1:
        target = brains[0] / "wiki" / "index.md"
    else:
        target = update_hub(project, brains)

    print("Brains: " + ", ".join(brain_name(project, brain) for brain in brains))
    print(f"Open: {target.relative_to(project)}")
    if should_open:
        open_in_obsidian(target)
    return target


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project", type=Path, default=Path.cwd())
    parser.add_argument("--brain", help="Brain name or path relative to the project")
    parser.add_argument("--no-open", action="store_true", help=argparse.SUPPRESS)
    args = parser.parse_args()
    try:
        prepare(args.project, args.brain, not args.no_open)
    except (OSError, subprocess.CalledProcessError, ValueError) as error:
        parser.error(str(error))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
